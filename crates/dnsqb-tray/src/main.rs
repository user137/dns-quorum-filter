// Four raw 32x32 RGBA blobs (4096 bytes each, no header), transparent
// background + a hexagon glyph in the per-status colour (green / amber / grey
// / red) — `tray_icon::Icon::from_rgba` takes raw pixels, not an encoded
// image, so compiling the blobs in avoids both a runtime filesystem read and
// an image-decode dependency (the same "everything in, no runtime asset I/O"
// choice `admin_ui.rs` makes for the embedded web UI). Generated by
// `assets/gen-icon.py` (`make_tray_glyph(size, colour)`), the single source
// for every project icon — re-run that script to regenerate, never hand-edit
// a .bin (T-191, extending T-183's single white glyph). `status::icon_colour`
// picks which one from the live `TrayStatus` + cert-trust state.
const ICON_GREEN: &[u8] = include_bytes!("../icons/tray-32-green-rgba.bin");
const ICON_AMBER: &[u8] = include_bytes!("../icons/tray-32-amber-rgba.bin");
const ICON_GREY: &[u8] = include_bytes!("../icons/tray-32-grey-rgba.bin");
const ICON_RED: &[u8] = include_bytes!("../icons/tray-32-red-rgba.bin");
const ICON_SIZE: u32 = 32;

/// The four decoded status icons, built once at startup. `tray_icon::Icon` is
/// `Clone`, so [`Self::get`] hands `set_icon` an owned copy per update.
struct TrayIcons {
    green: Icon,
    amber: Icon,
    grey: Icon,
    red: Icon,
}

impl TrayIcons {
    /// Decodes all four build-time blobs. `None` on any failure — a build-time
    /// asset that won't decode is fatal, the same handling the pre-T-191
    /// single-icon path had.
    fn build() -> Option<Self> {
        let decode = |bytes: &[u8]| Icon::from_rgba(bytes.to_vec(), ICON_SIZE, ICON_SIZE).ok();
        Some(Self {
            green: decode(ICON_GREEN)?,
            amber: decode(ICON_AMBER)?,
            grey: decode(ICON_GREY)?,
            red: decode(ICON_RED)?,
        })
    }

    fn get(&self, colour: IconColour) -> Icon {
        match colour {
            IconColour::Green => self.green.clone(),
            IconColour::Amber => self.amber.clone(),
            IconColour::Grey => self.grey.clone(),
            IconColour::Red => self.red.clone(),
        }
    }
}


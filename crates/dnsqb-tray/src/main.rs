/// Runs one trust-store action (`install`/`uninstall`) on its own throwaway
/// OS thread — unlike [`spawn_admin_action`], this is a synchronous local
/// `certutil` call, not an admin-HTTP-channel round trip, so no `tokio`
/// runtime is needed at all. Reports the outcome **both** ways: logged (as
/// every other action here does) and via a native dialog on this same
/// thread — this crate builds with `windows_subsystem = "windows"` (no
/// console), so a log line alone is invisible to a user who clicked a menu
/// item and is watching for a result. A silent failure here would leave the
/// user believing a trust-store change succeeded when it didn't — exactly
/// the "no on-screen indication" failure class this crate's own module doc
/// comment already names for "Зупинити фільтрацію" (advisor-caught before
/// commit, not written this way from the start).
fn spawn_trust_store_action<F, E>(
    action_name: &'static str,
    dialog_title: String,
    locale: String,
    action: F,
) where
    F: FnOnce() -> Result<String, E> + Send + 'static,
    E: std::fmt::Display,
{
    std::thread::spawn(move || match action() {
        Ok(outcome) => {
            tracing::info!("{action_name} succeeded: {outcome}");
            rfd::MessageDialog::new()
                .set_title(dialog_title)
                .set_description(i18n::t_args(
                    &locale,
                    "dialog.successTemplate",
                    &[("outcome", &outcome)],
                ))
                .set_level(rfd::MessageLevel::Info)
                .set_buttons(rfd::MessageButtons::Ok)
                .show();
        }
        Err(err) => {
            let err = err.to_string();
            tracing::warn!("{action_name} failed: {err}");
            rfd::MessageDialog::new()
                .set_title(dialog_title)
                .set_description(i18n::t_args(
                    &locale,
                    "dialog.failedTemplate",
                    &[("err", &err)],
                ))
                .set_level(rfd::MessageLevel::Error)
                .set_buttons(rfd::MessageButtons::Ok)
                .show();
        }
    });
}

/// [`spawn_trust_store_action`] plus a trust re-poll after the action returns
/// (T-191) — every cert menu item changes `CurrentUser\Root`, so the status
/// icon's colour needs to catch up. `request_recheck` fires *after* the
/// `certutil` call, not at click time: firing at click would race the
/// ~100–300 ms action and re-poll before the store actually changed.
fn spawn_cert_action<F, E>(
    action_name: &'static str,
    dialog_title: String,
    locale: String,
    trust: &TrustState,
    action: F,
) where
    F: FnOnce() -> Result<String, E> + Send + 'static,
    E: std::fmt::Display,
{
    let trust = trust.clone();
    spawn_trust_store_action(action_name, dialog_title, locale, move || {
        let outcome = action();
        trust.request_recheck();
        outcome
    });
}

/// Set by [`spawn_remove_all_and_quit`] once the report dialog is dismissed
/// and the app-data wipe helper is spawned — the event loop exits on its next
/// tick (a worker thread has no handle to `control_flow`).
static QUIT_REQUESTED: AtomicBool = AtomicBool::new(false);

/// T-195 — "Повністю видалити": clear the out-of-tree state, show the report,
/// then bring the whole app down and hand off the rest to the OS.
///
/// Not [`spawn_cert_action`]: the shutdown has to happen *after* the report
/// dialog, and `spawn_cert_action` shows its dialog after the closure returns.
/// Order: [`remove_all_local_state`] (cert + Credential Manager secrets, none
/// of them files in app-data) → report dialog → `stop.flag` + `quit.flag`
/// (the watcher stops `dnsqb-service` and exits on its next tick, exactly like
/// [`QUIT_APP_ID`]) → spawn the detached wipe helper (it waits for every
/// DNS-QF process to exit before deleting) → open Windows Settings →
/// `QUIT_REQUESTED` so this tray exits too.
fn spawn_remove_all_and_quit(app_data: PathBuf, locale: String) {
    std::thread::spawn(move || {
        let report = format_uninstall_report(&remove_all_local_state(Some(&app_data)), &locale);
        tracing::info!("remove-all-local-state finished:\n{report}");
        rfd::MessageDialog::new()
            .set_title(dialog_title(&i18n::t(&locale, "menu.removeAll")))
            .set_description(i18n::t_args(
                &locale,
                "uninstall.reportDialogTemplate",
                &[("report", &report)],
            ))
            .set_level(rfd::MessageLevel::Info)
            .set_buttons(rfd::MessageButtons::Ok)
            .show();
        if let Err(err) = set_stop_flag(&app_data) {
            tracing::warn!("could not write stop.flag: {err}");
        }
        if let Err(err) = set_quit_flag(&app_data) {
            tracing::warn!("could not write quit.flag: {err}");
        }
        self_uninstall::spawn_app_data_dir_wipe(&app_data);
        browser::open_windows_apps_settings();
        QUIT_REQUESTED.store(true, Ordering::SeqCst);
    });
}

/// One-shot first-run onboarding offer (T-188). Fires at most once per
/// process (`offered` latch), and only once the trust-watch thread has a
/// *confirmed* `certutil` reading — on a fresh MSIX install `cert.pem` does
/// not exist when the tray starts (T-187), so an earlier check would read the
/// optimistic seed, not the store. [`onboarding::should_offer_onboarding`] is
/// the pure predicate.
fn maybe_offer_onboarding(
    offered: &mut bool,
    app_data: &Path,
    port: u16,
    trust: &TrustState,
    trusted: bool,
    locale: &str,
) {
    if *offered {
        return;
    }
    let seen = onboarding::onboarding_seen(app_data);
    if onboarding::should_offer_onboarding(trust.is_confirmed(), trusted, seen) {
        *offered = true;
        run_setup_wizard(app_data, port, trust, locale);
    }
}

/// T-229: offers the nudge popup if due, then closes it (click or expiry).
/// One call site keeps this batch of tightly-coupled state out of `main`'s
/// own body — the same reason `refresh_tray`/`maybe_offer_onboarding` are
/// already their own functions.
fn drive_browser_nudge(
    offered: &mut bool,
    app_data: &Path,
    observed: TrayStatus,
    target: &tao::event_loop::EventLoopWindowTarget<()>,
    tray_icon: &TrayIcon,
    event: &tao::event::Event<()>,
    popup: &mut Option<nudge_popup::NudgePopup>,
) {
    maybe_offer_browser_nudge(offered, app_data, observed, target, tray_icon, popup);
    if popup
        .as_ref()
        .is_some_and(|p| p.should_close(event, nudge_popup::POPUP_LIFETIME))
    {
        *popup = None;
    }
}

/// One-shot "point your browser at this" nudge (T-229). Fires at most once
/// **per process** (`offered` latch) regardless of whether rendering
/// actually succeeds — a failed render (e.g. no monitor detected) is not
/// worth retrying every tick. The persisted `browser-nudge.seen` marker is
/// only written once [`nudge_popup::spawn`] actually returns a window — that
/// marker means "shown", not "decided to show", so a rendering failure can't
/// silently burn the one-shot latch a future launch could still use.
/// [`browser_nudge::should_offer_browser_nudge`] is the pure predicate.
fn maybe_offer_browser_nudge(
    offered: &mut bool,
    app_data: &Path,
    observed: TrayStatus,
    target: &tao::event_loop::EventLoopWindowTarget<()>,
    tray_icon: &TrayIcon,
    popup: &mut Option<nudge_popup::NudgePopup>,
) {
    if *offered {
        return;
    }
    let total_queries = match observed {
        TrayStatus::Filtering { total, .. } => Some(total),
        _ => None,
    };
    let seen = browser_nudge::browser_nudge_seen(app_data);
    let first_seen = browser_nudge::first_seen(app_data);
    if browser_nudge::should_offer_browser_nudge(SystemTime::now(), first_seen, total_queries, seen)
    {
        *offered = true;
        if let Some(window) = nudge_popup::spawn(target, tray_icon.rect()) {
            *popup = Some(window);
            browser_nudge::mark_browser_nudge_seen(app_data);
        } else {
            tracing::warn!("browser nudge popup failed to render");
        }
    }
}

/// Set while a [`run_setup_wizard`] welcome dialog is open, so the auto-offer
/// and the "Майстер налаштування" menu item can't stack two modal dialogs
/// (each able to spawn its own `ensure_installed`).
static WIZARD_ACTIVE: AtomicBool = AtomicBool::new(false);

/// The first-run wizard (T-188): a welcome dialog offering to install the
/// local certificate, then — on «Так» and a successful install — open the
/// browser-setup page. Runs entirely on a throwaway thread because `rfd`
/// dialogs block and both callers (the auto-offer above and the "Майстер
/// налаштування" menu item) are on the event-loop thread. Reuses
/// [`spawn_cert_action`] for the install half, so the trust icon re-polls
/// afterward for free. `onboarding.seen` is written on «Пізніше» and on a
/// *successful* install, never on a failed one (that should re-offer next
/// launch); the menu item is the manual re-entry regardless.
fn run_setup_wizard(app_data: &Path, port: u16, trust: &TrustState, locale: &str) {
    if WIZARD_ACTIVE.swap(true, Ordering::SeqCst) {
        return; // a welcome dialog is already open
    }
    let app_data = app_data.to_path_buf();
    let trust = trust.clone();
    let locale = locale.to_string();
    std::thread::spawn(move || {
        let proceed = confirm(
            &i18n::t(&locale, "onboarding.title"),
            &i18n::t(&locale, "onboarding.description"),
            rfd::MessageLevel::Info,
        );
        WIZARD_ACTIVE.store(false, Ordering::SeqCst);
        if !proceed {
            onboarding::mark_onboarding_seen(&app_data);
            return;
        }
        let cert_path = app_data.join("cert.pem");
        let url = format!("https://127.0.0.1:{port}/admin/ui");
        spawn_cert_action(
            "onboarding-install",
            dialog_title(&i18n::t(&locale, "menu.installCert")),
            locale.clone(),
            &trust,
            move || -> Result<String, dnsqb_service::TrustStoreError> {
                let outcome = ensure_installed(&cert_path)?;
                // Reached only on a successful install — a failure bails on the
                // `?` above with the marker still unwritten.
                onboarding::mark_onboarding_seen(&app_data);
                browser::open_in_default_browser(&url);
                Ok(trust_store_outcome_text(outcome, &locale))
            },
        );
    });
}

/// The one shape every "are you sure?" dialog below shares: [`dialog_title`]

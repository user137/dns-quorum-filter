/// What the consent step ended with; only [`ConsentStep::Declined`] changes
/// the certificate step's text (don't point the browser at the filter yet).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum ConsentStep {
    /// Not shown: not part of this run, service unreachable, or already given.
    NotAsked,
    /// The user said yes (whether or not it reached the disk).
    Granted,
    /// The user said no.
    Declined,
}

/// Wizard step 1 (T-286): asks the service whether consent is still missing
/// and who would see the domains, shows `dialog` with that list, and sends
/// the answer. Runs on the wizard's own thread. Nothing is asked when the
/// service can't be reached (no list to show, and the answer couldn't be
/// saved) or consent is already given. `consent-offer.seen` is written on
/// «Ні» and on a grant that reached the disk — never on a failure, so the
/// next launch asks again.
fn ask_for_consent(
    app_data: &Path,
    port: u16,
    dialog: rfd::MessageDialog,
    locale: &str,
) -> ConsentStep {
    let Ok(runtime) = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
    else {
        tracing::error!("failed to start a runtime for the consent step");
        return ConsentStep::NotAsked;
    };
    let client = match AdminClient::new(app_data, port) {
        Ok(client) => client,
        Err(err) => {
            tracing::warn!("consent step skipped, no admin client: {err}");
            return ConsentStep::NotAsked;
        }
    };
    let status = match runtime.block_on(client.status()) {
        Ok(status) => status,
        Err(err) => {
            tracing::warn!("consent step skipped, service unreachable: {err}");
            return ConsentStep::NotAsked;
        }
    };
    if status.domain_sharing_consent.is_given() {
        return ConsentStep::NotAsked;
    }
    let names: Vec<&str> = status
        .active_providers
        .iter()
        .map(|provider| provider.display_name.as_str())
        .collect();
    let providers_line = if names.is_empty() {
        i18n::t(locale, "onboarding.consentNoProviders")
    } else {
        i18n::t_args(
            locale,
            "onboarding.consentProvidersTemplate",
            &[("providers", &names.join(", "))],
        )
    };
    let description = i18n::t_args(
        locale,
        "onboarding.consentDescriptionTemplate",
        &[
            ("providersLine", &providers_line),
            ("privacyUrl", privacy_policy_url(locale)),
        ],
    );
    if dialog.set_description(description).show() != rfd::MessageDialogResult::Yes {
        onboarding::mark_consent_offer_seen(app_data);
        return ConsentStep::Declined;
    }
    // A fresh client, not `client`: while the dialog was open nothing drove
    // this current-thread runtime, so the pooled connection never saw the
    // service close it on its idle timeout, and the reused one failed
    // ("error sending request", Win10 VM smoke 2026-11-27).
    drop(client);
    let sent = match AdminClient::new(app_data, port) {
        Ok(client) => runtime.block_on(client.set_consent(true)),
        Err(err) => Err(err),
    };
    match sent {
        Ok(response) if response.persisted => onboarding::mark_consent_offer_seen(app_data),
        Ok(_) => tracing::warn!("consent granted but not saved; asking again next launch"),
        Err(err) => {
            let err = err.to_string();
            tracing::warn!("consent could not be sent: {err}");
            rfd::MessageDialog::new()
                .set_title(dialog_title(&i18n::t(locale, "onboarding.consentTitle")))
                .set_description(i18n::t_args(
                    locale,
                    "dialog.failedTemplate",
                    &[("err", &err)],
                ))
                .set_level(rfd::MessageLevel::Error)
                .set_buttons(rfd::MessageButtons::Ok)
                .show();
        }
    }
    ConsentStep::Granted
}

/// The one shape every "are you sure?" dialog below shares: [`dialog_title`]
/// for the header, always Yes/No buttons, always "did they pick Yes" as the
/// answer. Only the description text and severity actually differ per
/// dialog, so those stay ordinary arguments at each named `confirm_*`
/// call site below — this collapses the six-line `MessageDialog` builder
/// that used to be copy-pasted at every one of those sites (user question,
/// 2026-09-22: "чи можна винести це в одне місце" — this is that place),
/// without losing the named function + doc comment that explains *why*
/// that particular dialog exists, which a single generic call from the
/// menu-dispatch match arm would have.
fn confirm(action: &str, description: &str, level: rfd::MessageLevel) -> bool {
    confirm_dialog(action, description, level).show() == rfd::MessageDialogResult::Yes
}

/// The dialog [`confirm`] shows, unshown — for a caller that must attach an
/// owner window on the event-loop thread before showing it elsewhere.
fn confirm_dialog(action: &str, description: &str, level: rfd::MessageLevel) -> rfd::MessageDialog {
    rfd::MessageDialog::new()
        .set_title(dialog_title(action))
        .set_description(description)
        .set_level(level)
        .set_buttons(rfd::MessageButtons::YesNo)
}


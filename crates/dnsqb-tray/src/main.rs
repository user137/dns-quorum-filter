/// Which menu item was clicked — the pure `id -> intent` half of
/// [`handle_menu_event`], split out (T-202) so the routing is table-testable:
/// a mis-typed id constant, or a menu item added with no matching handler,
/// otherwise rides silently in an 823-line binary. Every side effect (confirm
/// dialogs, thread spawns, `control_flow`) stays in `handle_menu_event`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum MenuAction {
    /// Open `/admin/ui` in the default browser.
    OpenSettings,
    /// `POST /admin/reset` — clear the verdict cache and the query log.
    ResetCacheAndLog,
    /// Show the "Про програму" dialog.
    ShowAbout,
    /// Re-enter the first-run setup wizard.
    RunSetupWizard,
    /// Install the local TLS cert into `CurrentUser\Root` (behind a confirm).
    InstallCert,
    /// Remove the local TLS cert from the trust store (behind a confirm).
    UninstallCert,
    /// Regenerate the local TLS cert and re-install it (behind a confirm).
    RotateCert,
    /// Clear the trusted cert + stored secrets, wipe app-data, quit the app.
    RemoveAllLocalState,
    /// Pause filtering if it is running, resume it if paused (`stop.flag`).
    TogglePause,
    /// Relaunch the watchdog if it stopped.
    RestoreSupervision,
    /// Хвиля 13b: ask the watcher to reset its budget and start the service.
    RetryService,
    /// Хвиля 13b: move an invalid `resolver_config.toml` aside (behind a
    /// confirm), then retry.
    ResetConfig,
    /// Stop the service, the watchdog and this tray.
    QuitApp,
    /// Exit only this tray process; leave the service filtering.
    HideIcon,
    /// An id with no handler — preserves the old catch-all `_ => {}`.
    Unknown,
}

/// Maps a `muda` menu-item id to its [`MenuAction`]. Pure and total.
#[must_use]
fn menu_action_for(id: &str) -> MenuAction {
    match id {
        OPEN_SETTINGS_ID => MenuAction::OpenSettings,
        RESTART_ID => MenuAction::ResetCacheAndLog,
        ABOUT_ID => MenuAction::ShowAbout,
        SETUP_WIZARD_ID => MenuAction::RunSetupWizard,
        INSTALL_CERT_ID => MenuAction::InstallCert,
        UNINSTALL_CERT_ID => MenuAction::UninstallCert,
        ROTATE_CERT_ID => MenuAction::RotateCert,
        REMOVE_ALL_ID => MenuAction::RemoveAllLocalState,
        PAUSE_RESUME_ID => MenuAction::TogglePause,
        RESTORE_SUPERVISION_ID => MenuAction::RestoreSupervision,
        RETRY_SERVICE_ID => MenuAction::RetryService,
        RESET_CONFIG_ID => MenuAction::ResetConfig,
        QUIT_APP_ID => MenuAction::QuitApp,
        CLOSE_ID => MenuAction::HideIcon,
        _ => MenuAction::Unknown,
    }
}

fn handle_menu_event(
    id: &str,
    app_data: &Path,
    port: u16,
    control_flow: &mut ControlFlow,
    trust: &TrustState,
    locale: &str,
) {
    // T-303: a full removal is under way. «Відновити», «Відновити нагляд» or
    // «Спробувати ще раз» would start a service that recreates the secrets
    // being deleted; nothing in this menu is useful any more.
    if REMOVAL_IN_PROGRESS.load(Ordering::SeqCst) {
        tracing::info!("menu click ignored: full removal in progress");
        return;
    }
    match menu_action_for(id) {
        MenuAction::OpenSettings => {
            browser::open_in_default_browser(&format!("https://127.0.0.1:{port}/admin/ui"));
        }
        MenuAction::ResetCacheAndLog => {
            spawn_admin_action(app_data.to_path_buf(), port, "reset", |client| async move {
                client.reset().await.map(|_response| ())
            });
        }
        MenuAction::ShowAbout => show_about_dialog(port, locale),
        MenuAction::RunSetupWizard => rerun_setup_wizard(app_data, port, trust, locale),
        MenuAction::InstallCert => {
            if confirm_install_cert(locale) {
                let cert_path = app_data.join("cert.pem");
                let app_data_owned = app_data.to_path_buf();
                let locale = locale.to_string();
                spawn_cert_action(
                    "install",
                    dialog_title(&i18n::t(&locale, "menu.installCert")),
                    locale.clone(),
                    trust,
                    move || -> Result<String, dnsqb_service::TrustStoreError> {
                        let outcome = ensure_installed(&cert_path)?;
                        refresh_service_cert_trust(&app_data_owned, port);
                        Ok(trust_store_outcome_text(outcome, &locale))
                    },
                );
            }
        }
        MenuAction::UninstallCert => {
            if confirm_uninstall_cert(locale) {
                let locale = locale.to_string();
                spawn_cert_action(
                    "uninstall",
                    dialog_title(&i18n::t(&locale, "menu.uninstallCert")),
                    locale.clone(),
                    trust,
                    move || {
                        uninstall_trust_store()
                            .map(|()| i18n::t(&locale, "certOutcome.uninstalled"))
                    },
                );
            }
        }
        MenuAction::RotateCert => {
            if confirm_rotate_cert(locale) {
                let locale = locale.to_string();
                spawn_cert_action(
                    "rotate",
                    dialog_title(&i18n::t(&locale, "menu.rotateCert")),
                    locale.clone(),
                    trust,
                    move || {
                        rotate_certificate().map(|report| {
                            i18n::t_args(
                                &locale,
                                "certOutcome.rotateSuccessTemplate",
                                &[(
                                    "outcome",
                                    &trust_store_outcome_text(report.install_outcome, &locale),
                                )],
                            )
                        })
                    },
                );
            }
        }
        MenuAction::RemoveAllLocalState => {
            if REMOVE_ALL_PROMPT_ACTIVE.load(Ordering::SeqCst) {
                tracing::info!("a remove-all confirm from /admin/ui is already open");
            } else if confirm_remove_all_local_state(locale) {
                // Same latch as the /admin/ui path: no second prompt while the
                // app goes down.
                REMOVE_ALL_PROMPT_ACTIVE.store(true, Ordering::SeqCst);
                spawn_remove_all_and_quit(app_data.to_path_buf(), locale.to_string());
            }
        }
        // T-185 + T-193: pause = write `stop.flag` only. `dnsqb-service` polls
        // it (`pause_watch`) and serves every query through the unfiltered
        // baseline while it exists — the service stays up, the watchdog keeps
        // supervising it. Resume = remove the flag; `ensure_sibling_running` is
        // an idempotent no-op unless both the service and watcher died during
        // the pause. The label the user clicked tells us which.
        MenuAction::TogglePause => toggle_pause(app_data, locale),
        // T-185: bring the watchdog back if it stopped (idempotent — a no-op
        // when a watcher is already running). This is the only actionable
        // recovery for a dead watcher; there is no automatic one yet.
        MenuAction::RestoreSupervision => {
            ensure_sibling_running(app_data, InstanceRole::Watcher);
        }
        MenuAction::RetryService => request_service_retry(app_data),
        MenuAction::ResetConfig => reset_config_and_retry(app_data, locale),
        // T-185 / T-303: quit the whole app. Write `quit.flag` and exit the
        // tray; the service stops on it within a second and the watcher on its
        // next tick. No `stop.flag`: it would outlive the quit as a pause.
        MenuAction::QuitApp => {
            if confirm_quit(locale) {
                if let Err(err) = set_quit_flag(app_data) {
                    tracing::warn!("could not write quit.flag: {err}");
                }
                *control_flow = ControlFlow::Exit;
            }
        }
        // "Сховати іконку" only exits this process — dnsqb-service and the
        // watcher keep running, filtering stays on. "Вийти з DNS Quorum
        // Filter" above is the one that stops everything.
        MenuAction::HideIcon => *control_flow = ControlFlow::Exit,
        MenuAction::Unknown => {}
    }
}

/// Pause ↔ resume from the tray menu (T-185/T-193). Both outcomes are logged,
/// so `tray.log` shows when and by whom filtering was switched off (T-251).
fn toggle_pause(app_data: &Path, locale: &str) {
    if stop_flag_is_set(app_data) {
        clear_stop_flag(app_data);
        ensure_sibling_running(app_data, InstanceRole::Service);
        tracing::info!("filtering resumed by the user");
    } else if confirm_pause(locale) {
        match set_stop_flag(app_data) {
            Ok(()) => tracing::info!("filtering paused by the user"),
            Err(err) => tracing::warn!("could not write stop.flag: {err}"),
        }
    }
}

/// Runs one admin-channel action (`reset`/`shutdown`) on its own throwaway
/// OS thread with its own tiny runtime — these are rare, user-initiated
/// clicks, not a hot path, so building a fresh [`AdminClient`] per call is
/// fine here (same cadence the old `dnsqb-ui` Tauri commands already used) —
/// unlike [`status::spawn`]'s ~30x/minute poll, which specifically must not
/// rebuild one every tick.
fn spawn_admin_action<F, Fut>(app_data: PathBuf, port: u16, action_name: &'static str, action: F)
where
    F: FnOnce(AdminClient) -> Fut + Send + 'static,
    Fut: std::future::Future<Output = Result<(), AdminClientError>>,
{
    std::thread::spawn(move || {
        let Ok(runtime) = tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
        else {
            tracing::error!("failed to start a runtime for the {action_name} action");
            return;
        };
        runtime.block_on(async move {
            match AdminClient::new(&app_data, port) {
                Ok(client) => match action(client).await {
                    Ok(()) => tracing::info!("{action_name} succeeded"),
                    Err(err) => tracing::warn!("{action_name} failed: {err}"),
                },
                Err(err) => {
                    tracing::warn!("{action_name} failed to build an admin client: {err}");
                }
            }
        });
    });
}

/// Every native dialog's title, so a user with several DNS-QF popups open
/// (or a screenshot shared for support) can always see which app and which
/// build it came from at a glance (user request, 2026-09-22 v0.5.0 smoke
/// test) - one shared function so the format can't drift between call
/// sites the way the ten literal titles it replaced already had (`"dns-
/// quorum-filter"` lowercase-hyphenated on the About dialog vs `"DNS Quorum
/// Filter"` everywhere else).
fn dialog_title(action: &str) -> String {
    format!("DNS Quorum Filter {} — {action}", env!("CARGO_PKG_VERSION"))
}

/// Found in live smoke-testing (2026-09-22): the install/rotate success
/// dialogs used to forward `TrustStoreOutcome`'s raw `{:?}` ("Installed" /
/// "`AlreadyInstalled`") straight into a Ukrainian "Успішно: {outcome}"
/// sentence, mixing languages mid-sentence. `TrustStoreOutcome`/
/// `RotationReport`'s own `Debug`/`Display` are deliberately English (their
/// own doc comments: for logs) - this is the translation step that was
/// supposed to happen at the tray boundary but didn't. **T-151 Батч 5.5:**
/// generalized from a hardcoded Ukrainian match into a `t()` lookup, same
/// reasoning, any locale.
fn trust_store_outcome_text(outcome: TrustStoreOutcome, locale: &str) -> String {
    match outcome {
        TrustStoreOutcome::Installed => i18n::t(locale, "certOutcome.installed"),
        TrustStoreOutcome::AlreadyInstalled => i18n::t(locale, "certOutcome.alreadyInstalled"),
    }
}

/// Runs one trust-store action (`install`/`uninstall`) on its own throwaway
/// OS thread — unlike [`spawn_admin_action`], this is a synchronous local
/// `certutil` call, not an admin-HTTP-channel round trip, so no `tokio`
/// runtime is needed at all. Reports the outcome **both** ways: logged (as
/// every other action here does) and via a native dialog on this same
/// thread — this crate builds with `windows_subsystem = "windows"` (no
/// console), so a log line alone is invisible to a user who clicked a menu
/// item and is watching for a result. A silent failure here would leave the
/// user believing a trust-store change succeeded when it didn't — exactly
/// the "no on-screen indication" failure class this crate's own module doc
/// comment already names for "Зупинити фільтрацію" (advisor-caught before
/// commit, not written this way from the start).
fn spawn_trust_store_action<F, E>(
    action_name: &'static str,
    dialog_title: String,
    locale: String,
    action: F,
) where
    F: FnOnce() -> Result<String, E> + Send + 'static,
    E: std::fmt::Display,
{
    std::thread::spawn(move || {
        // T-303: one trust-store change at a time, and none once a full removal
        // has started - an install finishing after its sweep would leave a
        // trusted certificate behind. The dialog below runs without the lock.
        let result = {
            let _trust_store = TRUST_STORE_LOCK.lock();
            if REMOVAL_IN_PROGRESS.load(Ordering::SeqCst) {
                tracing::info!("{action_name} skipped: full removal in progress");
                return;
            }
            action()
        };
        show_trust_store_result(action_name, dialog_title, &locale, result);
    });
}

/// Serialises every tray trust-store change with «Повністю видалити» (T-303).
static TRUST_STORE_LOCK: parking_lot::Mutex<()> = parking_lot::Mutex::new(());

fn show_trust_store_result<E: std::fmt::Display>(
    action_name: &str,
    dialog_title: String,
    locale: &str,
    result: Result<String, E>,
) {
    match result {
        Ok(outcome) => {
            tracing::info!("{action_name} succeeded: {outcome}");
            rfd::MessageDialog::new()
                .set_title(dialog_title)
                .set_description(i18n::t_args(
                    locale,
                    "dialog.successTemplate",
                    &[("outcome", &outcome)],
                ))
                .set_level(rfd::MessageLevel::Info)
                .set_buttons(rfd::MessageButtons::Ok)
                .show();
        }
        Err(err) => {
            let err = err.to_string();
            tracing::warn!("{action_name} failed: {err}");
            rfd::MessageDialog::new()
                .set_title(dialog_title)
                .set_description(i18n::t_args(
                    locale,
                    "dialog.failedTemplate",
                    &[("err", &err)],
                ))
                .set_level(rfd::MessageLevel::Error)
                .set_buttons(rfd::MessageButtons::Ok)
                .show();
        }
    }
}

/// [`spawn_trust_store_action`] plus a trust re-poll after the action returns
/// (T-191) — every cert menu item changes `CurrentUser\Root`, so the status
/// icon's colour needs to catch up. `request_recheck` fires *after* the
/// `certutil` call, not at click time: firing at click would race the
/// ~100–300 ms action and re-poll before the store actually changed.
fn spawn_cert_action<F, E>(
    action_name: &'static str,
    dialog_title: String,
    locale: String,
    trust: &TrustState,
    action: F,
) where
    F: FnOnce() -> Result<String, E> + Send + 'static,
    E: std::fmt::Display,
{
    let trust = trust.clone();
    spawn_trust_store_action(action_name, dialog_title, locale, move || {
        let outcome = action();
        trust.request_recheck();
        outcome
    });
}

/// Set by [`spawn_remove_all_and_quit`] once the report dialog is dismissed
/// and the app-data wipe helper is spawned — the worker then wakes the event
/// loop, which exits (a worker thread has no handle to `control_flow`).
static QUIT_REQUESTED: AtomicBool = AtomicBool::new(false);

/// T-195 — "Повністю видалити": clear the out-of-tree state, show the report,
/// then bring the whole app down and hand off the rest to the OS.
///
/// Not [`spawn_cert_action`]: the shutdown has to happen *after* the report
/// dialog, and `spawn_cert_action` shows its dialog after the closure returns.
/// Order (T-303): `removing.flag` (no service or watcher starts while it is
/// fresh, whoever launches them — a tile click during the report included)
/// and `quit.flag` (the running service stops on it, the watcher exits on its
/// next tick) → wait until both are gone → under [`TRUST_STORE_LOCK`],
/// [`remove_all_local_state`] (cert + Credential Manager secrets) — so nothing
/// can mint a secret or re-trust the cert after it was deleted → report dialog
/// → spawn the detached wipe helper (it waits for this session's DNS-QF
/// processes to exit, then deletes the folder and the tombstone with it) →
/// open Windows Settings → `QUIT_REQUESTED` so this tray exits too.
fn spawn_remove_all_and_quit(app_data: PathBuf, locale: String) {
    REMOVAL_IN_PROGRESS.store(true, Ordering::SeqCst);
    std::thread::spawn(move || {
        if let Err(err) = set_removing_flag(&app_data) {
            tracing::warn!("could not write removing.flag: {err}");
        }
        if let Err(err) = set_quit_flag(&app_data) {
            tracing::warn!("could not write quit.flag: {err}");
        }
        if !wait_for_siblings_to_exit(&app_data, SIBLING_EXIT_WAIT) {
            tracing::warn!(
                "dnsqb-service or dnsqb-watcher still running after {SIBLING_EXIT_WAIT:?}; \
                 stopping them by PID"
            );
            force_stop_siblings(&app_data);
            if !wait_for_siblings_to_exit(&app_data, FORCED_EXIT_WAIT) {
                tracing::warn!(
                    "dnsqb-service or dnsqb-watcher survived a forced stop; removing local \
                     state anyway"
                );
            }
        }
        let removed = {
            let _trust_store = TRUST_STORE_LOCK.lock();
            remove_all_local_state(Some(&app_data))
        };
        let report = format_uninstall_report(&removed, &locale);
        tracing::info!("remove-all-local-state finished:\n{report}");
        rfd::MessageDialog::new()
            .set_title(dialog_title(&i18n::t(&locale, "menu.removeAll")))
            .set_description(i18n::t_args(
                &locale,
                "uninstall.reportDialogTemplate",
                &[("report", &report)],
            ))
            .set_level(rfd::MessageLevel::Info)
            .set_buttons(rfd::MessageButtons::Ok)
            .show();
        if let Err(failure_text) = self_uninstall::spawn_app_data_dir_wipe(&app_data, &locale) {
            rfd::MessageDialog::new()
                .set_title(dialog_title(&i18n::t(&locale, "menu.removeAll")))
                .set_description(failure_text)
                .set_level(rfd::MessageLevel::Warning)
                .set_buttons(rfd::MessageButtons::Ok)
                .show();
        }
        browser::open_windows_apps_settings();
        QUIT_REQUESTED.store(true, Ordering::SeqCst);
        wake_event_loop();
    });
}

/// Set for good once a full removal starts (T-303): the menu stops acting.
static REMOVAL_IN_PROGRESS: AtomicBool = AtomicBool::new(false);

/// The service drains for up to 5 s after `quit.flag`, the watcher exits on
/// its next 5 s tick; 15 s leaves room for a slow disk.
const SIBLING_EXIT_WAIT: Duration = Duration::from_secs(15);

/// After [`force_stop_siblings`] the OS ends the process almost at once.
const FORCED_EXIT_WAIT: Duration = Duration::from_secs(5);

/// The PID to force-stop: only one whose live process is the sibling binary
/// next to this tray, never a recycled PID or whatever exe the pid file names.
fn force_stop_target(record: Option<&PidFile>, check: Option<PidCheck>) -> Option<u32> {
    match (record, check) {
        (Some(record), Some(PidCheck::Alive)) => Some(record.pid),
        _ => None,
    }
}

/// Security review 2026-11-28: a service that outlived the graceful wait can
/// still answer `POST /admin/install-cert` — in its own process, outside
/// [`TRUST_STORE_LOCK`] — and re-trust the certificate after the sweep. Stop
/// both siblings by PID (`taskkill /F`, absolute path), watcher first so it
/// cannot respawn the service (which `removing.flag` blocks anyway).
///
/// `/T` (whole tree) for the service only: the likeliest reason it outlives
/// the wait is an in-flight `certutil -addstore` blocked on Windows' "install
/// this root?" prompt, and killing just the service would leave that prompt
/// up. Never `/T` for the watcher — it usually launched this tray, so a tree
/// kill would end the removal midway.
fn force_stop_siblings(app_data: &Path) {
    use std::os::windows::process::CommandExt as _;
    let current_exe = match std::env::current_exe() {
        Ok(path) => path,
        Err(err) => {
            tracing::warn!("cannot force-stop siblings: current exe unknown: {err}");
            return;
        }
    };
    for role in [InstanceRole::Watcher, InstanceRole::Service] {
        let Ok(expected) = resolve_sibling_path(&current_exe, role) else {
            continue;
        };
        // A missing or unreadable pid file means nothing to stop: each
        // process writes it right after taking its single-instance lock.
        let record = read_pid_file(app_data, role).ok();
        let check = record
            .as_ref()
            .map(|record| verify_pid_alive(record.pid, &expected));
        let Some(pid) = force_stop_target(record.as_ref(), check) else {
            continue;
        };
        let mut taskkill = std::process::Command::new(browser::system32_exe("taskkill.exe"));
        taskkill.args(["/PID", &pid.to_string(), "/F"]);
        if matches!(role, InstanceRole::Service) {
            taskkill.arg("/T");
        }
        match taskkill
            .creation_flags(self_uninstall::CREATE_NO_WINDOW)
            .status()
        {
            Ok(status) if status.success() => {}
            Ok(status) => tracing::warn!("taskkill of {role:?} exited with {status}"),
            Err(err) => tracing::warn!("could not run taskkill for {role:?}: {err}"),
        }
    }
}

/// Poll the service and watcher pid files until neither names a live process,
/// or `budget` runs out. `true` = both gone.
fn wait_for_siblings_to_exit(app_data: &Path, budget: Duration) -> bool {
    let deadline = Instant::now() + budget;
    loop {
        let alive = [InstanceRole::Service, InstanceRole::Watcher]
            .into_iter()
            .any(|role| sibling_is_alive(app_data, role));
        if !alive {
            return true;
        }
        if Instant::now() >= deadline {
            return false;
        }
        std::thread::sleep(Duration::from_millis(250));
    }
}

/// Set while a remove-all confirm requested from `/admin/ui` is open, so a
/// second click (or a second tab, or the menu item) can't stack another one.
static REMOVE_ALL_PROMPT_ACTIVE: AtomicBool = AtomicBool::new(false);

/// Хвиля 14 (T-268): the `/admin/ui` danger-zone button asks for the same
/// «Повністю видалити» as the menu item, via a fresh `remove-all.flag`
/// (`dnsqb_service::lifecycle`). The tray shows its own native confirm — a
/// request from the browser alone never removes anything — on a throwaway
/// thread, above the browser through a hidden topmost owner (T-269: the tray
/// is a background process, Windows would open the dialog behind the page
/// the user just clicked in). Requests that arrive while it is open are
/// consumed and dropped. «Так» → [`spawn_remove_all_and_quit`], unchanged.
fn poll_remove_all_request(
    owner: &mut Option<tao::window::Window>,
    app_data: &Path,
    locale: &str,
    target: &tao::event_loop::EventLoopWindowTarget<()>,
) {
    if owner.is_some() && !REMOVE_ALL_PROMPT_ACTIVE.load(Ordering::SeqCst) {
        *owner = None;
    }
    if take_remove_all_flag(app_data, SystemTime::now()) != RemoveAllTake::Fresh {
        return;
    }
    if QUIT_REQUESTED.load(Ordering::SeqCst)
        || REMOVE_ALL_PROMPT_ACTIVE.swap(true, Ordering::SeqCst)
    {
        tracing::info!("dropped a remove-all request: one is already open or running");
        return;
    }
    *owner = topmost_owner(target);
    let mut dialog = confirm_dialog(
        &i18n::t(locale, "menu.removeAll"),
        &i18n::t(locale, "confirm.removeAll.description"),
        rfd::MessageLevel::Warning,
    );
    if let Some(owner) = owner.as_ref() {
        dialog = dialog.set_parent(owner);
    }
    let app_data = app_data.to_path_buf();
    let locale = locale.to_string();
    std::thread::spawn(move || {
        if dialog.show() == rfd::MessageDialogResult::Yes {
            tracing::info!("full removal requested from /admin/ui confirmed by the user");
            // The latch stays set: the app is going down, nothing may prompt
            // again before `QUIT_REQUESTED` lands.
            spawn_remove_all_and_quit(app_data, locale);
        } else {
            tracing::info!("full removal requested from /admin/ui declined by the user");
            REMOVE_ALL_PROMPT_ACTIVE.store(false, Ordering::SeqCst);
        }
        wake_event_loop();
    });
}

/// One-shot first-run onboarding offers (T-188, T-286). Two independent
/// steps, each with its own per-process latch: consent (T-286) fires on a
/// confirmed "not granted" reading from the service, the certificate step
/// (T-188) once the trust-watch thread has a *confirmed* `certutil` reading —
/// on a fresh MSIX install `cert.pem` does not exist when the tray starts
/// (T-187), so an earlier check would read the optimistic seed. Both due on
/// the same tick share one wizard; while a wizard is open nothing is decided,
/// so a step that becomes due meanwhile is offered after it closes, not lost.
/// [`onboarding::check_consent_offer`] / [`onboarding::check_onboarding`] are
/// the pure predicates.
fn maybe_offer_onboarding(
    state: &mut OnboardingOffer,
    app_data: &Path,
    port: u16,
    trust: &TrustState,
    readings: OnboardingReadings,
    locale: &str,
    target: &tao::event_loop::EventLoopWindowTarget<()>,
) {
    if WIZARD_ACTIVE.load(Ordering::SeqCst) {
        return;
    }
    state.owner = None;
    let consent = if state.consent_settled {
        OfferCheck::Never
    } else {
        onboarding::check_consent_offer(readings.consent, || {
            onboarding::consent_offer_seen(app_data)
        })
    };
    let cert = if state.cert_settled {
        OfferCheck::Never
    } else {
        onboarding::hold_cert_until_consent(consent, || {
            onboarding::check_onboarding(trust.is_confirmed(), readings.cert_trusted, || {
                onboarding::onboarding_seen(app_data)
            })
        })
    };
    state.consent_settled |= consent != OfferCheck::NotYet;
    state.cert_settled |= cert != OfferCheck::NotYet;
    let steps = WizardSteps {
        consent: consent == OfferCheck::Offer,
        cert: cert == OfferCheck::Offer,
    };
    if steps.consent || steps.cert {
        state.owner = topmost_owner(target);
        run_setup_wizard(app_data, port, trust, locale, state.owner.as_ref(), steps);
    }
}

/// The automatic first-run offers (T-188, T-286) and the hidden owner of
/// their dialog.
struct OnboardingOffer {
    consent_settled: bool,
    cert_settled: bool,
    owner: Option<tao::window::Window>,
}

/// What this tick knows for [`maybe_offer_onboarding`]: the cert-trust flag
/// and the service's consent answer (`None` = no answer yet).
#[derive(Debug, Clone, Copy)]
struct OnboardingReadings {
    cert_trusted: bool,
    consent: Option<bool>,
}

impl OnboardingReadings {
    fn new(cert_trusted: bool, observed: TrayStatus) -> Self {
        Self {
            cert_trusted,
            consent: observed.consent_reading(),
        }
    }
}

/// Which wizard steps to show (T-286).
#[derive(Debug, Clone, Copy)]
struct WizardSteps {
    consent: bool,
    cert: bool,
}

/// T-269: an automatic offer comes from a background process — the tray was
/// started by the watcher, not by a click — so Windows refuses it the
/// foreground and the welcome dialog opened behind the user's browser. A
/// hidden always-on-top owner puts the dialog above other windows without
/// stealing focus (no synthetic input, unlike `tao`'s `set_focus`). Kept
/// alive while the dialog is open; `None` just means the old behaviour.
fn topmost_owner(
    target: &tao::event_loop::EventLoopWindowTarget<()>,
) -> Option<tao::window::Window> {
    tao::window::WindowBuilder::new()
        .with_visible(false)
        .with_always_on_top(true)
        .build(target)
        .map_err(|err| tracing::warn!("could not create the welcome dialog's owner: {err}"))
        .ok()
}

/// Per-process state of the browser nudge's automatic offer (ARCH-19 a):
/// `settled` closes once the decision is final, `first_seen` is the stamp
/// read once at startup instead of on every tick; `locale` picks the
/// popup's text.
struct NudgeLatch {
    settled: bool,
    first_seen: Option<SystemTime>,
    locale: &'static str,
}

/// T-229: offers the nudge popup if due, then closes it (click or expiry).
/// One call site keeps this batch of tightly-coupled state out of `main`'s
/// own body — the same reason `refresh_tray`/`maybe_offer_onboarding` are
/// already their own functions.
fn drive_browser_nudge(
    latch: &mut NudgeLatch,
    app_data: &Path,
    observed: TrayStatus,
    target: &tao::event_loop::EventLoopWindowTarget<()>,
    tray_icon: &TrayIcon,
    event: &tao::event::Event<()>,
    popup: &mut Option<nudge_popup::NudgePopup>,
) {
    maybe_offer_browser_nudge(latch, app_data, observed, target, tray_icon, popup);
    if popup
        .as_ref()
        .is_some_and(|p| p.should_close(event, nudge_popup::POPUP_LIFETIME))
    {
        *popup = None;
    }
}

/// One-shot "point your browser at this" nudge (T-229). Fires at most once
/// **per process** (`NudgeLatch::settled`) regardless of whether rendering
/// actually succeeds — a failed render (e.g. no monitor detected) is not
/// worth retrying every tick. The persisted `browser-nudge.seen` marker is
/// only written once [`nudge_popup::spawn`] actually returns a window — that
/// marker means "shown", not "decided to show", so a rendering failure can't
/// silently burn the one-shot latch a future launch could still use. The
/// other writer is [`browser_nudge::retire_if_browser_in_use`]: a poll that
/// saw queries retires the nudge on disk, so a reboot can't revive it.
/// [`browser_nudge::check_browser_nudge`] is the pure predicate.
fn maybe_offer_browser_nudge(
    latch: &mut NudgeLatch,
    app_data: &Path,
    observed: TrayStatus,
    target: &tao::event_loop::EventLoopWindowTarget<()>,
    tray_icon: &TrayIcon,
    popup: &mut Option<nudge_popup::NudgePopup>,
) {
    if latch.settled {
        return;
    }
    let total_queries = match observed {
        TrayStatus::Filtering { total, .. } => Some(total),
        _ => None,
    };
    let check = browser_nudge::check_browser_nudge(
        SystemTime::now(),
        latch.first_seen,
        total_queries,
        || browser_nudge::browser_nudge_seen(app_data),
    );
    if check != OfferCheck::NotYet {
        latch.settled = true;
    }
    if check == OfferCheck::Never {
        browser_nudge::retire_if_browser_in_use(app_data, total_queries);
    }
    if check == OfferCheck::Offer {
        if let Some(window) = nudge_popup::spawn(target, tray_icon.rect(), latch.locale) {
            *popup = Some(window);
            browser_nudge::mark_browser_nudge_seen(app_data);
        } else {
            tracing::warn!("browser nudge popup failed to render");
        }
    }
}

/// Set while a [`run_setup_wizard`] welcome dialog is open, so the auto-offer
/// and the "Майстер налаштування" menu item can't stack two modal dialogs
/// (each able to spawn its own `ensure_installed`).
static WIZARD_ACTIVE: AtomicBool = AtomicBool::new(false);

/// The first-run wizard (T-188, T-286). Step 1 (T-286) asks for consent to
/// send domains to the providers ([`ask_for_consent`]); step 2 (T-188)
/// offers to install the local certificate, then — on «Так» and a successful
/// install — opens the browser-setup page. Runs on a throwaway thread because
/// `rfd` dialogs block and both callers (the auto-offer above and the
/// "Майстер налаштування" menu item) are on the event-loop thread; the
/// dialogs are built here, on that thread, so they can take `owner`. Reuses
/// [`spawn_cert_action`] for the install half, so the trust icon re-polls
/// afterward for free. `onboarding.seen` is written on «Пізніше» and on a
/// *successful* install, never on a failed one (that should re-offer next
/// launch); the menu item is the manual re-entry regardless.
fn run_setup_wizard(
    app_data: &Path,
    port: u16,
    trust: &TrustState,
    locale: &str,
    owner: Option<&tao::window::Window>,
    steps: WizardSteps,
) {
    if WIZARD_ACTIVE.swap(true, Ordering::SeqCst) {
        return; // a welcome dialog is already open
    }
    let with_owner = |dialog: rfd::MessageDialog| match owner {
        Some(owner) => dialog.set_parent(owner),
        None => dialog,
    };
    let consent_dialog = steps.consent.then(|| {
        with_owner(confirm_dialog(
            &i18n::t(locale, "onboarding.consentTitle"),
            "",
            rfd::MessageLevel::Info,
        ))
    });
    // The description is set after the consent step: a declined consent
    // changes what the user should (not) do with the browser next.
    let cert_dialog = steps.cert.then(|| {
        with_owner(confirm_dialog(
            &i18n::t(locale, "onboarding.title"),
            "",
            rfd::MessageLevel::Info,
        ))
    });
    let app_data = app_data.to_path_buf();
    let trust = trust.clone();
    let locale = locale.to_string();
    std::thread::spawn(move || {
        let consent = consent_dialog.map_or(ConsentStep::NotAsked, |dialog| {
            ask_for_consent(&app_data, port, dialog, &locale)
        });
        let cert_key = if consent == ConsentStep::Declined {
            "onboarding.descriptionNoConsent"
        } else {
            "onboarding.description"
        };
        let proceed = cert_dialog.map(|dialog| {
            dialog.set_description(i18n::t(&locale, cert_key)).show()
                == rfd::MessageDialogResult::Yes
        });
        WIZARD_ACTIVE.store(false, Ordering::SeqCst);
        match proceed {
            None => return,
            Some(false) => {
                onboarding::mark_onboarding_seen(&app_data);
                return;
            }
            Some(true) => {}
        }
        let cert_path = app_data.join("cert.pem");
        let url = format!("https://127.0.0.1:{port}/admin/ui");
        spawn_cert_action(
            "onboarding-install",
            dialog_title(&i18n::t(&locale, "menu.installCert")),
            locale.clone(),
            &trust,
            move || -> Result<String, dnsqb_service::TrustStoreError> {
                let outcome = ensure_installed(&cert_path)?;
                // Reached only on a successful install — a failure bails on the
                // `?` above with the marker still unwritten.
                onboarding::mark_onboarding_seen(&app_data);
                refresh_service_cert_trust(&app_data, port);
                browser::open_in_default_browser(&url);
                Ok(trust_store_outcome_text(outcome, &locale))
            },
        );
    });
}

/// The service learns about a certificate the tray installed only on its
/// next 60 s trust poll, so the settings page opened right after the wizard
/// read "Certificate not installed" for up to a minute (Win10 VM smoke
/// 2026-11-27). `/admin/install-cert` on an already-trusted certificate shows
/// no dialog and refreshes the service's cached state at once. Best effort:
/// on failure the poll still catches up.
fn refresh_service_cert_trust(app_data: &Path, port: u16) {
    let Ok(runtime) = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
    else {
        tracing::warn!("no runtime to refresh the service's certificate state");
        return;
    };
    let result =
        AdminClient::new(app_data, port).and_then(|client| runtime.block_on(client.install_cert()));
    if let Err(err) = result {
        tracing::warn!("service certificate state not refreshed: {err}");
    }
}

/// The "Майстер налаштування" menu item: every step. The consent step
/// re-checks the service itself and is skipped when consent is already given.
fn rerun_setup_wizard(app_data: &Path, port: u16, trust: &TrustState, locale: &str) {
    let steps = WizardSteps {
        consent: true,
        cert: true,
    };
    run_setup_wizard(app_data, port, trust, locale, None, steps);
}

